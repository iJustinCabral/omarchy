  def test_foreign_limine_drift_refuses(self):
    self.kernel_update()
    updated = self.path(PAIR.SINGLE.LIMINE).read_bytes()
    drifts = {
      "timeout": lambda raw: raw.replace(b"timeout: 3", b"timeout: 9"),
      "default": lambda raw: raw.replace(b"default_entry: 2", b"default_entry: 1"),
      "cmdline": lambda raw: raw.replace(b"cmdline: root=/dev/mapper/root rw", b"cmdline: root=/dev/mapper/root rw quiet"),
      "foreign entry": lambda raw: raw.replace(b"/EFI fallback", b"/Foreign\nprotocol: efi\npath: boot():/x.efi\n/EFI fallback"),
      "fallback": lambda raw: raw.replace(b"BOOTX64.EFI", b"OTHER.EFI"),
      "trailing": lambda raw: raw + b"# trailing\n",
    }
    for name, drift in drifts.items():
      with self.subTest(name):
        self.write(PAIR.SINGLE.LIMINE, drift(updated))
        self.refuses("Limine changed beyond")
    self.write(PAIR.SINGLE.LIMINE, updated)
    self.assertEqual(self.retire()["state"], "retired")

  def test_unrecognised_snapshot_text_and_modified_block_refuse(self):
    self.kernel_update()
    updated = self.path(PAIR.SINGLE.LIMINE).read_bytes()
    self.write(PAIR.SINGLE.LIMINE, updated.replace(b"     comment: 4 snapshots\n", b"     comment: 4 snapshots\n     surprise: yes\n"))
    self.refuses("snapshot region")
    self.write(PAIR.SINGLE.LIMINE, updated.replace(b"comment: One-shot T2 hibernation source", b"comment: edited"))
    self.refuses("pair text")
    self.write(PAIR.SINGLE.LIMINE, updated + self.block)
    self.refuses("duplicated")

  def test_stale_production_hash_refuses(self):
    self.write("boot/EFI/Linux/omarchy_linux-t2.efi", self.new_production)
