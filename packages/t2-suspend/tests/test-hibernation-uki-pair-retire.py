HERE = Path(__file__).resolve().parents[1]


def load(name, path):
  spec = importlib.util.spec_from_file_location(name, path)
  module = importlib.util.module_from_spec(spec)
  spec.loader.exec_module(module)
  return module


PAIR = load("retire_pair", HERE / "experiments/stage-hibernation-uki-pair.py")
MACHINE = "0123456789abcdef0123456789abcdef"
STEPS = ("archive", "journal", "custody", "limine", "image-source", "image-restore", "backup", "receipt", "record")


def sha(data):
  return hashlib.sha256(data).hexdigest()


def b2(data):
  return hashlib.blake2b(data).hexdigest()


def efi_string(value):
  return b"\x07\x00\x00\x00" + (value + "\x00").encode("utf-16-le")


def fake_uki(release):
  """A minimal PE image whose only section is .uname holding the release (what an Arch UKI carries)."""
  header = b"MZ" + b"\0" * 0x3a + (0x40).to_bytes(4, "little") + b"PE\0\0"
  header += (0x8664).to_bytes(2, "little") + (1).to_bytes(2, "little") + b"\0" * 12 + (0xf0).to_bytes(2, "little") + b"\0" * 2
  header += b"\0" * 0xf0
  data = release.encode()
  section = b".uname\0\0" + len(data).to_bytes(4, "little") + b"\0" * 4 + (0x200).to_bytes(4, "little") + (0x400).to_bytes(4, "little") + b"\0" * 16
  image = (header + section).ljust(0x400, b"\0") + data
  return image, release


def region(count, tag):
  if count == 0:
    return ""
  text = "     //Snapshots\n     ### Auto-generated by limine-snapper-sync\n     comment: " + str(count) + " snapshots\n"
  for index in range(1, count + 1):
    text += (
      "     ///" + str(index) + " │ 2026-09-17 17:35:4" + str(index) + "\n     comment: 4.0." + str(index) + "-1\n     ////linux-t2\n"
      "     comment: kernel-id=linux-t2\n     protocol: efi\n"
      "     path: boot():/" + MACHINE + "/limine_history/omarchy_linux-t2.efi_sha256_" + tag * 64 + "#" + tag * 128 + "\n"
      "     cmdline: root=/dev/mapper/root rootflags=subvol=/@/.snapshots/" + str(index) + "/snapshot\n"
    )
  return text + "\n"


def release_of(production):
  return production[0x400:].decode() if production[:2] == b"MZ" else None


def limine_text(production, count, tag):
  release = release_of(production)
  comment = "" if release is None else "  comment: Kernel version: " + release + "\n  comment: kernel-id=linux-t2 \n"
  return (
    "timeout: 3\ndefault_entry: 2\n"
    "/+Omarchy\n### This OS entry is auto-generated by limine-entry-tool\ncomment: Omarchy\n"
    "comment: machine-id=" + MACHINE + " order-priority=50 \n"
    "  //linux-t2\n  ### This kernel entry is auto-generated by limine-entry-tool\n" + comment + "  protocol: efi\n  path: boot():/EFI/Linux/omarchy_linux-t2.efi#" + b2(production) + "\n"
    "  cmdline: root=/dev/mapper/root rw\n\n" + region(count, tag)
    + "/EFI fallback\nprotocol: efi\npath: boot():/EFI/BOOT/BOOTX64.EFI\n"
  )


class Retire(unittest.TestCase):
  def setUp(self):
    self.temp = tempfile.TemporaryDirectory()
    self.addCleanup(self.temp.cleanup)
    self.root = Path(self.temp.name) / "root"
    self.old_production = fake_uki("7.2.6-arch2-Watanare-T2-2-t2")[0]
    self.new_production = fake_uki("7.2.7-arch1-Watanare-T2-2-t2")[0]
    self.path("boot/EFI/Linux/omarchy_linux-t2.efi").parent.mkdir(parents=True)
    self.path("boot/EFI/Linux/omarchy_linux-t2.efi").write_bytes(self.old_production)
    self.original = limine_text(self.old_production, 2, "a").encode()
    self.images = {}
    for role in PAIR.IMAGES:
      data = (role + " uki").encode()
      self.images[role] = {
        "entry_id": PAIR.entry_id(role, sha(data)), "sha256": sha(data), "blake2": b2(data),
        "provenance_sha256": "f" * 64, "experiment_id": "x-" + role, "data": data,
      }
      self.write(PAIR.IMAGES[role], data)
    self.block = PAIR.stage_block(self.images)
    self.staged = self.original + self.block
    self.write(PAIR.SINGLE.LIMINE, self.staged)
    self.write(PAIR.BACKUP, self.original)
    self.receipt = {
      "state": "staged", "kernel_policy": "production-linux-unchanged",
      "production_uki_sha256": sha(self.old_production),
      "original_limine_sha256": sha(self.original), "staged_limine_sha256": sha(self.staged),
      "images": {role: {k: v for k, v in self.images[role].items() if k != "data"} for role in PAIR.IMAGES},
    }
    self.write(PAIR.RECEIPT, json.dumps(self.receipt, indent=2, sort_keys=True).encode() + b"\n")
    self.receipt_raw = self.path(PAIR.RECEIPT).read_bytes()
    evidence = self.path(PAIR.STATE / "s4-vectors")
    evidence.mkdir()
    (evidence / "guard").write_text("consumed")
    self.write(PAIR.SINGLE.SELECTED, efi_string("Omarchy.linux-t2"))
    self.write(PAIR.MAINTENANCE, b"{}")
    self.write(PAIR.PHYSICAL_LOCK, b"")
    self.path(PAIR.PHYSICAL_LOCK).chmod(0o600)
    self.path(PAIR.DB_LOCK).parent.mkdir(parents=True, exist_ok=True)
    self.updated_limine = None

  def path(self, relative):
    return self.root / relative

  def write(self, relative, data):
    path = self.path(relative)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)

  def kernel_update(self):
    """What limine-mkinitcpio and limine-snapper-sync do: new UKI, new hash line, new snapshots."""
    self.write("boot/EFI/Linux/omarchy_linux-t2.efi", self.new_production)
    self.updated_limine = limine_text(self.new_production, 4, "c").encode()
    self.write(PAIR.SINGLE.LIMINE, self.updated_limine + self.block)

  def retire(self, **arguments):
    return PAIR.retire(self.root, **arguments)

  def refuses(self, expected, action=None, foreign_db_lock=False):
    before = self.snapshot()
    with self.assertRaises(ValueError) as context:
      (action or self.retire)()
    self.assertIn(expected, str(context.exception))
    self.assertEqual(self.snapshot(), before, "refusal must not change anything")
    self.assertEqual(self.path(PAIR.DB_LOCK).exists(), foreign_db_lock)

  def snapshot(self):
    return {
      str(path.relative_to(self.root)): (path.read_bytes() if path.is_file() else None)
      for path in sorted(self.root.rglob("*")) if path.is_file() or path.is_dir()
    }

  def assert_retired(self):
    self.assertEqual(self.path(PAIR.SINGLE.LIMINE).read_bytes(), self.updated_limine)
    self.assertEqual(self.path("boot/EFI/Linux/omarchy_linux-t2.efi").read_bytes(), self.new_production)
    for role in PAIR.IMAGES:
      self.assertFalse(self.path(PAIR.IMAGES[role]).exists())
    self.assertFalse(self.path(PAIR.RECEIPT).exists())
    self.assertFalse(self.path(PAIR.BACKUP).exists())
    self.assert_custody()
    self.assertEqual((self.path(PAIR.STATE / "s4-vectors") / "guard").read_text(), "consumed")
    self.assertFalse(self.path(PAIR.DB_LOCK).exists())

  def custody_paths(self):
    shared = PAIR.custody()
    return self.path(PAIR.PRODUCT_STATE / shared.RETIREMENT_NAME), self.path(PAIR.PRODUCT_STATE / shared.RETIRED_RECEIPT_NAME)

  def assert_custody(self):
    """The exact custody contract: retained receipt bytes and a strict record chaining to them, mode 0600."""
    shared = PAIR.custody()
    record, copy = self.custody_paths()
    self.assertEqual(copy.read_bytes(), self.receipt_raw)
    value = json.loads(record.read_bytes())
    self.assertEqual(set(value), shared.RETIREMENT_KEYS)
    self.assertEqual(value, {"protocol": "omarchy-t2-pair-retirement-v1", "retired_receipt_sha256": sha(self.receipt_raw),
                             "source_sha256": self.images["source"]["sha256"], "restore_sha256": self.images["restore"]["sha256"]})
    shared.check(value, copy.read_bytes())
    for path in (record, copy): self.assertEqual(path.stat().st_mode & 0o777, 0o600)

  def chain_holds(self):
    """The maintenance chain can always resolve the receipt: the live one, or the custody copy that a valid record binds."""
    live = self.path(PAIR.RECEIPT)
    if live.exists() and live.read_bytes() == self.receipt_raw: return True
    record, copy = self.custody_paths()
    try: PAIR.custody().check(json.loads(record.read_bytes()), copy.read_bytes())
    except (OSError, ValueError): return False
    return copy.read_bytes() == self.receipt_raw

  def test_custody_uses_the_shared_contract_and_is_written_before_the_receipt_is_removed(self):
    self.kernel_update()
    seen = []
    def hook(name):
      seen.append((name, self.chain_holds(), self.path(PAIR.RECEIPT).exists(), all(path.exists() for path in self.custody_paths())))
    self.retire(step_hook=hook)
    self.assertTrue(all(item[1] for item in seen), seen)  # never a moment the marker's receipt is unresolvable
    self.assertEqual([item[0] for item in seen], list(STEPS))
    by = {item[0]: item for item in seen}
    self.assertFalse(by["journal"][3])  # nothing before the custody step
    self.assertTrue(by["custody"][2] and by["custody"][3])  # both custody files exist while the live receipt still does
    self.assertFalse(by["receipt"][2])
    self.assert_custody()
    consumer = importlib.util.spec_from_file_location("custody_consumer", HERE / "hibernate/boot_policy_transition.py")
    transition = importlib.util.module_from_spec(consumer)
    consumer.loader.exec_module(transition)
    self.assertEqual((transition.RETIREMENT.name, transition.RETIRED_RECEIPT.name), (PAIR.custody().RETIREMENT_NAME, PAIR.custody().RETIRED_RECEIPT_NAME))
    self.assertEqual(transition.RETIREMENT_KEYS, PAIR.custody().RETIREMENT_KEYS)

  def test_the_shared_image_paths_equal_the_stagers(self):
    self.assertEqual({role: str(path) for role, path in PAIR.IMAGES.items()}, PAIR.custody().IMAGE_PATHS)

  def test_stale_custody_of_a_previous_generation_is_replaced_atomically(self):
    self.kernel_update()
    record, copy = self.custody_paths()
    self.write(PAIR.PRODUCT_STATE / PAIR.custody().RETIRED_RECEIPT_NAME, b'{"images": "an older receipt"}')
    self.write(PAIR.PRODUCT_STATE / PAIR.custody().RETIREMENT_NAME, b'{"protocol": "stale"}')
    calls = []
    real = PAIR.atomic_write
    def watch(path, data, mode):
      calls.append(path.name)
      real(path, data, mode)
    PAIR.atomic_write = watch
    try: self.retire()
    finally: PAIR.atomic_write = real
    self.assertIn(record.name, calls)
    self.assertIn(copy.name, calls)
    self.assertLess(calls.index(copy.name), calls.index(record.name))  # copy first, the record commits it
    self.assert_custody()
    self.assertEqual([name for name in os.listdir(record.parent) if name.startswith(".pair-")], [])

  def test_custody_paths_must_be_regular_files(self):
    self.kernel_update()
    record, copy = self.custody_paths()
    record.symlink_to(self.path("etc-target"))
    with self.assertRaises(ValueError): self.retire()
    self.assertTrue(self.path(PAIR.RECEIPT).exists())  # the live receipt survived the refusal
    record.unlink()
    copy.mkdir()
    with self.assertRaises(ValueError): self.retire()
    self.assertTrue(self.path(PAIR.RECEIPT).exists())
    copy.rmdir()
    self.assertEqual(self.retire()["state"], "retired")
    self.assert_retired()

  def test_a_crash_around_the_custody_write_reruns_to_the_same_bytes(self):
    for step in ("journal", "custody", "limine", "receipt"):
      with self.subTest(step=step):
        self.tearDown_fixture()
        self.setUp()
        self.kernel_update()
        def hook(name, step=step):
          if name == step: raise RuntimeError("crash")
        with self.assertRaises(RuntimeError): self.retire(step_hook=hook)
        self.assertTrue(self.chain_holds())
        self.assertEqual(self.retire()["state"], "retired")
        self.assert_retired()

  def test_rollback_removes_the_custody_it_wrote_and_survives_a_crash_between_the_two_files(self):
    for crash in (None, "custody-record-removed", "custody-removed"):
      with self.subTest(crash=crash):
        self.tearDown_fixture()
        self.setUp()
        self.kernel_update()
        def stop(name):
          if name == "receipt": raise RuntimeError("interrupted")
        with self.assertRaises(RuntimeError): self.retire(step_hook=stop)
        self.assertTrue(all(path.exists() for path in self.custody_paths()))
        def hook(name, crash=crash):
          self.assertTrue(self.chain_holds(), name)
          if name == crash: raise RuntimeError("rollback crash")
        if crash:
          with self.assertRaises(RuntimeError): PAIR.retire_rollback(self.root, step_hook=hook)
          self.assertTrue(self.chain_holds())
        self.assertEqual(PAIR.retire_rollback(self.root, step_hook=hook if not crash else None)["state"], "retirement-rolled-back")
        self.assertFalse(any(path.exists() for path in self.custody_paths()))
        self.assertEqual(self.path(PAIR.RECEIPT).read_bytes(), self.receipt_raw)
        self.assertEqual(self.retire()["state"], "retired")
        self.assert_retired()

  def test_rollback_leaves_custody_that_does_not_chain_to_this_receipt(self):
    self.kernel_update()
    def stop(name):
      if name == "receipt": raise RuntimeError("interrupted")
    with self.assertRaises(RuntimeError): self.retire(step_hook=stop)
    record, copy = self.custody_paths()
    record.write_bytes(json.dumps({"retired_receipt_sha256": "1" * 64}).encode())
    copy.write_bytes(b"another generation's receipt")
    PAIR.retire_rollback(self.root)
    self.assertTrue(record.exists() and copy.exists())

  def test_happy_path_archives_then_removes_only_our_entries(self):
    self.kernel_update()
    result = self.retire()
    self.assertEqual(result["state"], "retired")
    self.assert_retired()
    record = result["retirement"]
    self.assertEqual(record["retired_receipt_sha256"], sha(self.receipt_raw))
    self.assertEqual(record["old_production_uki_sha256"], sha(self.old_production))
    self.assertEqual(record["new_production_uki_sha256"], sha(self.new_production))
    archive = self.path(PAIR.ARCHIVE_ROOT) / record["archive"]
    self.assertEqual(oct(archive.stat().st_mode & 0o777), "0o700")
    self.assertEqual(oct(archive.parent.stat().st_mode & 0o777), "0o700")
    manifest = json.loads((archive / "manifest.json").read_text())
    self.assertEqual(set(manifest["files"]), {
      "receipt.json", "limine.conf.before", "limine.conf.at-retirement", "images/source.efi", "images/restore.efi",
    })
    for name, digest in manifest["files"].items():
      self.assertEqual(sha((archive / name).read_bytes()), digest)
    self.assertEqual((archive / "images/source.efi").read_bytes(), self.images["source"]["data"])
    self.assertEqual((archive / "limine.conf.before").read_bytes(), self.original)
    self.assertEqual((archive / "receipt.json").read_bytes(), self.receipt_raw)
    self.assertEqual(sha((archive / "limine.conf.at-retirement").read_bytes()), record["limine_before_sha256"])
    self.assertEqual(oct((archive / "receipt.json").stat().st_mode & 0o777), "0o600")

