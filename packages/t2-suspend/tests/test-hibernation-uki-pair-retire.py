  def test_every_durable_write_can_fail_and_rerun_completes(self):
    writer = PAIR.atomic_write
    self.tearDown_fixture()
    calls = 0
    for fail_at in range(1, 30):
      self.setUp()
      self.kernel_update()
      counter = [0]

      def failing(path, data, mode, fail_at=fail_at, counter=counter):
        counter[0] += 1
        if counter[0] == fail_at:
          raise RuntimeError("injected write failure")
        writer(path, data, mode)

      PAIR.atomic_write = failing
      try:
        try:
          self.retire()
          finished = True
        except RuntimeError:
          finished = False
      finally:
        PAIR.atomic_write = writer
      if finished:
        calls = fail_at
        self.assert_retired()
        break
      self.assertEqual(self.retire()["state"], "retired", fail_at)
      self.assert_retired()
      self.tearDown_fixture()
