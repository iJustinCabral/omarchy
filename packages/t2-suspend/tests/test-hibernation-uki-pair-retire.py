  def test_backup_tamper_refuses(self):
    self.kernel_update()
    self.write(PAIR.BACKUP, self.original + b"#")
    self.refuses("backup changed")

  def test_unknown_state_files_and_bad_receipt_state_refuse(self):
    self.kernel_update()
    self.write(PAIR.STATE / "stray", b"x")
    self.refuses("unknown files")
    self.path(PAIR.STATE / "stray").unlink()
    for state in ("rolling-back", "preparing"):
      receipt = dict(self.receipt, state=state)
      self.write(PAIR.RECEIPT, json.dumps(receipt).encode())
      self.refuses("cannot be retired")

  def test_held_locks_refuse(self):
    self.kernel_update()
    self.write(PAIR.DB_LOCK, b"")
    self.refuses("db.lck is held", foreign_db_lock=True)
    self.path(PAIR.DB_LOCK).unlink()
    descriptor = os.open(self.path(PAIR.PHYSICAL_LOCK), os.O_RDONLY)
    try:
      fcntl.flock(descriptor, fcntl.LOCK_EX)
      self.refuses("physical lock")
    finally:
      os.close(descriptor)
    self.assertEqual(self.retire()["state"], "retired")

  def test_rolled_back_receipt_with_changed_production_retires_without_images(self):
    self.assertEqual(PAIR.rollback(self.root)["state"], "rolled-back")
    self.assertEqual(self.path(PAIR.SINGLE.LIMINE).read_bytes(), self.original)
    self.write("boot/EFI/Linux/omarchy_linux-t2.efi", self.new_production)
    self.updated_limine = limine_text(self.new_production, 4, "c").encode()
    self.write(PAIR.SINGLE.LIMINE, self.updated_limine)
    plan = self.retire(dry_run=True)
    self.assertFalse(plan["limine_block_present"])
    self.assertEqual(self.retire()["retirement"]["receipt_state"], "rolled-back")
    self.assert_retired()

  def test_retire_does_not_change_production_or_other_state(self):
    self.kernel_update()
    self.write("boot/EFI/Linux/other.efi", b"other")
    self.write(PAIR.STATE / "test-resume-vectors/v", b"vector")
    self.retire()
    self.assertEqual(self.path("boot/EFI/Linux/other.efi").read_bytes(), b"other")
    self.assertEqual(self.path(PAIR.STATE / "test-resume-vectors/v").read_bytes(), b"vector")

  def test_second_retirement_of_identical_receipt_gets_its_own_archive(self):
    self.kernel_update()
    first = self.retire()["retirement"]
    for role in PAIR.IMAGES:
      self.write(PAIR.IMAGES[role], self.images[role]["data"])
    self.write(PAIR.BACKUP, self.original)
    self.write(PAIR.RECEIPT, self.receipt_raw)
    self.write(PAIR.SINGLE.LIMINE, self.updated_limine + self.block)
    second = self.retire()["retirement"]
    self.assertNotEqual(first["archive"], second["archive"])
    self.assertTrue(first["archive"].endswith("-0") and second["archive"].endswith("-1"))
    self.assert_retired()


