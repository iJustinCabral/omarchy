class ReactivationBytes(unittest.TestCase):
  """The one-line boot-config transform, its canonical checks and the churned-deactivation intent."""
  def setUp(self):
    self.fixture = Transitions("test_activation_then_exact_fallback_preserves_all_authority_and_evidence")
    self.fixture.setUp()
    self.addCleanup(self.fixture.doCleanups)
    self.f, self.root = self.fixture.f, self.fixture.root
    self.entry = self.f.policy["source_entry_id"]

  def test_transform_changes_exactly_one_line_of_the_current_bytes_and_is_canonically_prepare(self):
    proposal = T.P.prepare(self.f.before, self.f.raw)["after"]
    for numbers, reverse in (([], False), ([1], False), ([1, 2], False), ([2, 3, 4], True), ([9, 10, 11, 12, 13], False)):
      with self.subTest(numbers=numbers):
        current = with_snapshots(self.f.before, numbers, reverse)
        self.assertEqual(T.P.limine_canonical(current), self.f.before)
        new = T._to_source_default(current, self.entry)
        self.assertEqual(new, current.replace(b"default_entry: 2\n", b"default_entry: " + self.entry.encode() + b"\n", 1))
        self.assertEqual(T.P.limine_canonical(new), T.P.limine_canonical(proposal))
        T._one_line_change(current, new)
        if not numbers: self.assertEqual(new, proposal)  # no region: the exact approved bytes
        else: self.assertNotEqual(new, proposal)  # never the approved bytes: that would drop the snapshot entries
        self.assertEqual(T._to_stock_default(new, self.entry), current)  # reversal restores the same bytes
        self.assertEqual(T.P.validate({**T.P.prepare(self.f.before, self.f.raw)["policy"], "approved": True}, self.f.before, new, self.f.raw), self.f.before)

  def test_transform_refuses_ambiguous_or_foreign_default_lines(self):
    current = with_snapshots(self.f.before, [1, 2])
    for label, raw in (("second stock default", current + b"default_entry: 2\n"), ("remembered entry", current.replace(b"default_entry: 2\n", b"default_entry: 2\nremember_last_entry: yes\n", 1)),
                       ("indented default", current.replace(b"default_entry: 2\n", b" default_entry: 2\n", 1)), ("no default", current.replace(b"default_entry: 2\n", b"", 1)),
                       ("default inside the region", current.replace(b"     comment: 4.0.2-1\n", b"     default_entry: 2\n", 1)), ("already source", T._to_source_default(current, self.entry))):
      with self.subTest(label), self.assertRaises(ValueError): T._to_source_default(raw, self.entry)
    for label, raw in (("stock", current), ("other entry", current.replace(b"default_entry: 2\n", b"default_entry: other\n", 1))):
      with self.subTest("reverse " + label), self.assertRaises(ValueError): T._to_stock_default(raw, self.entry)
    with self.assertRaisesRegex(ValueError, "exactly one line"): T._one_line_change(b"a\nb\n", b"x\ny\n")
    with self.assertRaisesRegex(ValueError, "exactly one line"): T._one_line_change(b"a\nb\n", b"a\nb\nc\n")

  def test_rollback_never_yields_non_stock_bytes(self):
    current = with_snapshots(self.f.before, [1])
    new = T._to_source_default(current, self.entry)
    broken = new.replace(b"/+Omarchy\n", b"/+Broken\n", 1)
    with self.assertRaises(ValueError): T._to_stock_default(broken, self.entry)  # the guard's stock validator refuses the result

  def test_reactivation_pending_recognizes_only_its_own_protocol(self):
    self.assertFalse(T.reactivation_pending(self.root))
    path = self.root / T.PENDINGS["activation"]
    for raw, expected in ((b"garbage", False), (T._encoded({"protocol": "omarchy-t2-runtime-upgrade-intent-v2"}), False), (T._encoded({"protocol": T.REACTIVATION_SCHEMA}), True)):
      self.fixture.f.write(T.PENDINGS["activation"], raw)
      self.assertIs(T.reactivation_pending(self.root), expected)
      path.unlink()


