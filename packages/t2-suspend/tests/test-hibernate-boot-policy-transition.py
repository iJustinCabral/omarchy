def snapshot_block(numbers, reverse=False):
  """A limine-snapper-sync style //Snapshots sub-tree nested under the Omarchy OS entry."""
  lines = ["", "     //Snapshots", "     ### Auto-generated by limine-snapper-sync", "     comment: %d snapshots" % len(numbers)]
  for number in (reversed(numbers) if reverse else numbers):
    lines += ["     ///%d \u2502 2026-09-%02d 17:35:47" % (number, number), "     comment: 4.0.2-1", "     ////linux-t2",
              "     comment: Kernel version: 7.1.8-test", "     comment: kernel-id=linux-t2", "     protocol: efi",
              "     path: boot():/" + MACHINE + "/limine_history/omarchy_linux-t2.efi_sha256_%s#%s" % (("%02x" % number) * 32, ("%02x" % number) * 64),
              "     cmdline: root=/dev/mapper/root rootflags=subvol=/@/.snapshots/%d/snapshot rw" % number]
  return "\n".join(lines) + "\n"


def with_snapshots(raw, numbers, reverse=False):
  """Replace any existing snapshot sub-tree with the given one, ahead of the staged pair block."""
  text, marker = raw.decode(), "# BEGIN omarchy T2 hibernation pair"
  if "\n     //Snapshots" in text: text = text[:text.index("\n     //Snapshots")] + "\n" + text[text.index(marker):]
  index = text.index(marker)
  if not numbers: return text.encode()
  return (text[:index].rstrip("\n") + "\n" + snapshot_block(numbers, reverse) + text[index:]).encode()


